"""Данные гейта покрытия: что учитываем и что проверено руками.

Отделено от `test_spec_coverage.py` намеренно. Код гейта не меняется часто,
а эти два множества правятся почти в каждом change'е и могут разрастаться до сотен
строк: держать их в одном файле с проверками — значит каждый раз читать диффом
данные вперемешку с логикой. Комментарии здесь несут не меньше смысла, чем
сами строки, поэтому формат — Python-модуль, а не JSON: в JSON объяснить,
почему сценарий закрыт распиской, негде.

Модуль называется не `test_*.py` сознательно: `marked()` в гейте ищет маркеры
регуляркой по файлам `test_*.py`, и строки из `MANUAL` засчитались бы как
покрытие тестом.
"""

from __future__ import annotations

# Capability, попавшие под учёт покрытия.
#
# Список расширяется осознанно, по одной capability за раз. Спеки, написанные
# до введения механизма, сюда не вносятся задним числом: гейт был бы красным
# с первого дня, и первое, что с ним сделали бы, — отключили.
#
# Новая capability добавляется здесь в тот же момент, когда появляется её
# дельта-спека. Забыть — значит не увидеть её сценарии ни в отчёте покрытия,
# ни в гейте на архивации.
#
# Пример заполнения:
#     TRACKED = {"sales-plan-control", "sales-plan-create"}
TRACKED: set[str] = set()

# Сценарии, проверенные не автотестом. Ключ — путь
# `<capability>/<Requirement>/<Scenario>` дословно, как в спеке;
# значение — путь к протоколу прогона относительно корня репозитория.
#
# Это расписка, а не исключение. Она ничего не проверяет: гейт лишь следит,
# что сценарий и протокол существуют. Ценность записи — в комментарии над
# ней, объясняющем, почему автотест здесь невозможен или бессмыслен
# (поведение модели, вёрстка в браузере, свойство всей цепочки доставки).
#
# Заполнять MANUAL сознательно неудобно: добавить расписку должно быть дороже,
# чем написать тест. Перечитывать её надо при архивации change'а — расписка
# действительна ровно настолько, насколько актуален протокол, на который она
# ссылается.
#
# Пример заполнения:
#     MANUAL = {
#         # Ранжирование строк по вкладу в разрыв проверяется глазами:
#         # автотест на подставных данных проверил бы подставную сортировку.
#         "sales-plan-control/Список приоритетов/Крупная категория с малым процентом":
#             "docs/sales-plan-control-check.md",
#     }
MANUAL: dict[str, str] = {}
